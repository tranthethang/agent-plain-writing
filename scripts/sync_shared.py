#!/usr/bin/env python3
"""Build the sub-skills in skills/ from shared/.

    python3 scripts/sync_shared.py          write the generated files
    python3 scripts/sync_shared.py --check  exit 1 when any file differs

Python 3.7+, standard library only.
"""
import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ROOT / "shared"
SKILLS = ROOT / "skills"
TYPES = ["tech-blog", "essay", "api-design", "user-guide", "common"]
FAMILY = {"essay": "creative"}  # every other type uses "plain"
NOTE = "<!-- Generated from shared/ by scripts/sync_shared.py. Do not edit this file. -->"
COPIES = [("languages", "languages"), ("scripts/check_style.py", "scripts/check_style.py"),
          ("templates", "templates")]


def read(path):
    return path.read_text(encoding="utf-8")


def build_skill_md(doc_type):
    text = read(SHARED / "doc-types" / f"{doc_type}.md")
    m = re.match(r"---\n(.*?)\n---\n\n?(.*)", text, re.S)
    if not m:
        raise SystemExit(f"shared/doc-types/{doc_type}.md has no frontmatter")
    front, type_body = m.groups()
    core = read(SHARED / "skill-core.md").replace("{{type}}", doc_type)
    family = read(SHARED / "families" / f"{FAMILY.get(doc_type, 'plain')}.md")
    parts = [core.rstrip(), family.rstrip(), type_body.rstrip()]
    return f"---\n{front}\n---\n\n{NOTE}\n\n" + "\n\n".join(parts) + "\n"


def expected():
    """Return {absolute path: bytes} for every generated file."""
    files = {}
    for t in TYPES:
        out = SKILLS / f"agent-plain-writing-{t}"
        files[out / "SKILL.md"] = build_skill_md(t).encode("utf-8")
        for src_rel, dst_rel in COPIES:
            src = SHARED / src_rel
            paths = sorted(p for p in src.rglob("*") if p.is_file()) if src.is_dir() else [src]
            for p in paths:
                if "__pycache__" in p.parts or p.name == ".DS_Store":
                    continue
                rel = p.relative_to(src) if src.is_dir() else Path()
                if src_rel == "languages" and len(rel.parts) >= 2 and rel.parts[1] == "examples" and p.name != f"{t}.md":
                    continue
                files[out / dst_rel / rel] = p.read_bytes()
    return files


def actual_extras(files):
    """Files in the copied folders that shared/ does not have."""
    extras = []
    for t in TYPES:
        out = SKILLS / f"agent-plain-writing-{t}"
        for _, dst_rel in COPIES:
            dst = out / dst_rel
            if dst.is_dir():
                extras += [p for p in dst.rglob("*") if p.is_file()
                           and "__pycache__" not in p.parts and p.name != ".DS_Store"
                           and p not in files]
    return extras


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when a generated file differs")
    args = ap.parse_args()
    files = expected()
    extras = actual_extras(files)
    if args.check:
        bad = [p for p, data in files.items() if not p.is_file() or p.read_bytes() != data]
        bad += extras
        for p in bad:
            print(f"differs or missing: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if bad else 0
    for p in extras:
        p.unlink()
    for p, data in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    print(f"wrote {len(files)} files, removed {len(extras)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
